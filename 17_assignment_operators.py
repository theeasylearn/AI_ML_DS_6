#assignment operators
num1 = int(input("Enter value for num1"))
num2 = int(input("Enter value for num2"))

# num1 = num1 + num2 or 
num1+=num2
print(f"num1 = {num1}")
# num1 = num1 - num2
num1-=num2
print(f"num1 = {num1}")
# num1 = num1 * num2
num1*=num2
print(f"num1 = {num1}")
# num1 = num1 / num2
num1/=num2
print(f"num1 = {num1}")
# num1 = num1 % num2
num1%=num2
print(f"num1 = {num1}")
# num1 = num1 ** num2
num1**=num2
print(f"num1 = {num1}")
# num1 = num1 // num2
num1//=num2
print(f"num1 = {num1}") 